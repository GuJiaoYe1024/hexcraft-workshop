def write_hex(rid, rarity, weight, mods, event):
    j = {"rarity": rarity, "weight": weight}
    if mods:
        j["mods"] = [{"attr": k, "perLevel": v} for k, v in mods.items()]
    if event:
        j["event"] = event
    p = os.path.join(DATA, rid + ".json")
    json.dump(j, io.open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=2)

def patch_lang(lang, adds):
    p = os.path.join(LANG, lang + ".json")
    d = json.load(io.open(p, encoding="utf-8"))
    d.update(adds)
    json.dump(d, io.open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    return len(d)

zh, en = {}, {}
for rid, rarity, weight, mods, event, zn, zd, enm, end in HEXES:
    write_hex(rid, rarity, weight, mods, event)
    zh["hexcraft.hextech.%s.name" % rid] = zn
    zh["hexcraft.hextech.%s.desc" % rid] = zd
    en["hexcraft.hextech.%s.name" % rid] = enm
    en["hexcraft.hextech.%s.desc" % rid] = end

nz = patch_lang("zh_cn", zh)
ne = patch_lang("en_us", en)
